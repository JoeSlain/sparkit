import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const authorDir = fileURLToPath(new URL('../drizzle/', import.meta.url));
const targetDir = fileURLToPath(new URL('../../../supabase/migrations/', import.meta.url));
const check = process.argv.includes('--check');
const files = (await readdir(authorDir)).filter((name) => /^\d{14}_.+\.sql$/.test(name)).sort();
if (!files.length)
  throw new Error('No Drizzle SQL found. Run pnpm --filter @agency/db generate first.');
for (const file of files) {
  const sql = await readFile(path.join(authorDir, file), 'utf8');
  const target = path.join(targetDir, file);
  const expected = `-- Generated by Drizzle; edit the schema and generate a new migration.\n${sql}`;
  let existing;
  try {
    existing = await readFile(target, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  // Never rewrite deployed SQL. New changes require a new migration.
  if (existing !== undefined && existing !== expected)
    throw new Error(`Export differs: ${file}. Published migrations are immutable.`);
  if (existing === undefined) {
    if (check) throw new Error(`Missing export: ${file}. Run pnpm --filter @agency/db export.`);
    await writeFile(target, expected, { flag: 'wx' });
  }
}
const exports = (await readdir(targetDir)).filter((name) => /^\d{14}_.+\.sql$/.test(name));
for (const file of exports) {
  const contents = await readFile(path.join(targetDir, file), 'utf8');
  if (contents.startsWith('-- Generated by Drizzle;') && !files.includes(file))
    throw new Error(`Orphan export: ${file}`);
}
console.log(
  `${check ? 'Verified' : 'Exported'} ${files.length} Drizzle migration(s). Supabase CLI applies them.`,
);
